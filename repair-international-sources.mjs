itf=itf.replace(/url:`[^`]*acceptance-list\/`/,"url:ITF_SITE+link+(link.endsWith('/')?'':'/')+'acceptance-list/'");
if(itf.includes('{{https'))throw Error('URL ITF ancora compressa');
await fs.writeFile('itf-entries.mjs',itf);
